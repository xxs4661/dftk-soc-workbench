#!/usr/bin/env bash

set -euo pipefail

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
REPOSITORY_ROOT=$(CDPATH= cd -- "$SCRIPT_DIR/.." && pwd)
WORK_DIR="$REPOSITORY_ROOT/.work"
DFTK_DIR="$WORK_DIR/DFTK.jl"
PSEUDOPOTENTIALIO_DIR="$WORK_DIR/PseudoPotentialIO.jl"
STATE_FILE="$WORK_DIR/source-state.env"
STATUS_FILE="$WORK_DIR/bootstrap-status.env"

mkdir -p "$WORK_DIR"

write_status() {
    local status=$1
    local exit_code=$2
    local detail=$3
    local status_temporary
    status_temporary=$(mktemp "$WORK_DIR/.bootstrap-status.XXXXXX")
    cat >"$status_temporary" <<EOF
STATUS='$status'
EXIT_CODE='$exit_code'
RECORDED_AT_UTC='$(date -u '+%Y-%m-%dT%H:%M:%SZ')'
DETAIL='$detail'
EOF
    mv "$status_temporary" "$STATUS_FILE"
}

sources_are_ready() {
    [[ -f "$STATE_FILE" ]] || return 1
    [[ -d "$DFTK_DIR/.git" ]] || return 1
    [[ -d "$PSEUDOPOTENTIALIO_DIR/.git" ]] || return 1

    # This file is generated by fetch_sources.sh and contains only quoted source metadata.
    # shellcheck disable=SC1090
    source "$STATE_FILE"
    [[ "$(git -C "$DFTK_DIR" rev-parse HEAD)" == "$DFTK_COMMIT" ]] || return 1
    [[ "$(git -C "$PSEUDOPOTENTIALIO_DIR" rev-parse HEAD)" == "$PSEUDOPOTENTIALIO_COMMIT" ]] || return 1
}

if sources_are_ready; then
    echo "Reusing the locked source checkouts from fetch_sources.sh."
else
    "$SCRIPT_DIR/fetch_sources.sh"
fi

if ! command -v julia >/dev/null 2>&1; then
    write_status "BLOCKED" 3 "Julia is not available; no setup was fabricated."
    echo "BLOCKED: Julia is not available. Install a compatible official Julia release and rerun this script." >&2
    exit 3
fi

before_status=$(git -C "$DFTK_DIR" status --porcelain --untracked-files=all)
if [[ -n "$before_status" ]]; then
    write_status "FAIL" 4 "The DFTK checkout was not clean before bootstrap."
    echo "FAIL: the DFTK checkout has local changes before bootstrap." >&2
    echo "$before_status" >&2
    exit 4
fi

mkdir -p "$WORK_DIR/julia-depot"
echo "Instantiating and precompiling the locked DFTK project. Initial Julia compilation may be quiet for several minutes."

set +e
JULIA_DEPOT_PATH="$WORK_DIR/julia-depot" \
    JULIA_PKG_PRECOMPILE_AUTO=0 \
    julia --startup-file=no --project="$DFTK_DIR" \
    -e 'using Pkg; Pkg.instantiate(); Pkg.precompile()'
bootstrap_exit=$?
set -e

if [[ $bootstrap_exit -ne 0 ]]; then
    write_status "FAIL" "$bootstrap_exit" "Julia dependency instantiation or precompilation failed."
    echo "FAIL: DFTK bootstrap exited with $bootstrap_exit." >&2
    exit "$bootstrap_exit"
fi

after_status=$(git -C "$DFTK_DIR" status --porcelain --untracked-files=all)
if [[ -n "$after_status" ]]; then
    write_status "FAIL" 5 "Bootstrap changed files in the DFTK checkout."
    echo "FAIL: bootstrap changed files in the DFTK checkout." >&2
    echo "$after_status" >&2
    exit 5
fi

write_status "PASS" 0 "Dependency instantiation and precompilation completed successfully."
echo "PASS: DFTK dependency instantiation and precompilation completed successfully."
